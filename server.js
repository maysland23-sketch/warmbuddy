// Helper: try to set up VAPID with given keys, returns {ok, error}
function trySetupVapid(publicKey, privateKey, subject) {
  try {
    webpush.setVapidDetails(subject, publicKey, privateKey);
    return { ok: true, error: null };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

// 1st attempt: use env-provided keys
if (VAPID_PUBLIC_KEY && VAPID_PRIVATE_KEY) {
  const result = trySetupVapid(VAPID_PUBLIC_KEY, VAPID_PRIVATE_KEY, VAPID_SUBJECT);
  if (result.ok) {
    vapidInitialized = true;
    console.log('🔔 Web Push initialized (env keys)');
  } else {
    console.error('❌ VAPID env keys failed:', result.error);
    console.error('   PUBLIC_KEY length:', VAPID_PUBLIC_KEY.length, 'chars, starts with:', VAPID_PUBLIC_KEY.slice(0, 8) + '...');
    console.error('   PRIVATE_KEY length:', VAPID_PRIVATE_KEY.length, 'chars');
    console.error('   SUBJECT:', VAPID_SUBJECT);
    // Don't reset — keep for diagnosis. Will try auto-generation as fallback.
    vapidError = result.error;
  }
}

// 2nd attempt: auto-generate if env keys are missing or invalid
if (!vapidInitialized) {
  const generated = webpush.generateVAPIDKeys();
  const genResult = trySetupVapid(generated.publicKey, generated.privateKey, VAPID_SUBJECT);
  if (genResult.ok) {
    VAPID_PUBLIC_KEY = generated.publicKey;
    VAPID_PRIVATE_KEY = generated.privateKey;
    vapidInitialized = true;
    vapidAutoGenerated = true;
    console.log('🔔 Web Push initialized (auto-generated keys)');
    console.log('   ⚠️  Auto-generated keys change on each deploy — subscriptions break.');
    console.log('   Add these to Vercel env vars for stability:');
    console.log('   VAPID_PUBLIC_KEY=' + VAPID_PUBLIC_KEY);
    console.log('   VAPID_PRIVATE_KEY=' + VAPID_PRIVATE_KEY);
  } else {
    console.error('❌ VAPID auto-generation also failed:', genResult.error);
    vapidError = (vapidError ? vapidError + '; ' : '') + 'Auto-gen also failed: ' + genResult.error;
  }
}

