/**
 * Apply backend-side passive desire growth (mirrors frontend checkPassiveDrives).
 * Only confirmation grows passively (+5/hour "悬置"); all drives decay -10 if >24h.
 * Uses _lastBackendGrowth (independent from frontend's lastPassiveCheck).
 * Returns the updated desireState object, or null if no change was made.
 */
function applyBackendDesireGrowth(ds, pid, cfg) {
  const now = new Date();
  const lastGrowth = ds._lastBackendGrowth
    ? new Date(ds._lastBackendGrowth)
    : (ds.lastCheck ? new Date(ds.lastCheck) : null);
  const fallback = lastGrowth || now;
  const hoursPassed = (now - fallback) / (1000 * 60 * 60);

  // Rate-limit: check at most every 10 min
  if (hoursPassed < 1/6) return null;

  const drives = ds.drives || {};
  let changed = false;

  // ── confirmation: pure time-based, driven by lastUserMessageTime ──
  // lastUserMessageTime is set by the frontend ONLY when the user sends a message.
  // Falls back to chatSummaryUpdatedAt for backward compatibility.
  // If the user hasn't chatted for hours, confirmation = hours_since × 5 (capped 100).
  const lastChatTimeRaw = (cfg && cfg.lastUserMessageTime) || (cfg && cfg.chatSummaryUpdatedAt) || null;
  const lastChatTime = lastChatTimeRaw
    ? new Date(lastChatTimeRaw)
    : lastGrowth;  // fallback for projects without either field
  const hoursSinceChat = Math.max(0, (now - lastChatTime) / (1000 * 60 * 60));
  const timeBasedConfirmation = Math.min(100, Math.floor(hoursSinceChat * 5));
  if (drives.confirmation !== timeBasedConfirmation) {
    console.log(`[cron] ${pid}: confirmation ${drives.confirmation||0} → ${timeBasedConfirmation} (${hoursSinceChat.toFixed(1)}h since last chat)`);
    drives.confirmation = timeBasedConfirmation;
    changed = true;
  }

  // Decay: non-confirmation drives -10 if >24h since last check (floor at 0)
  if (hoursPassed >= 24) {
    for (const k of Object.keys(drives)) {
      if (k === 'confirmation') continue;  // confirmation is time-based, not decayed
      drives[k] = Math.max(0, (drives[k] || 0) - 10);
    }
    changed = true;
  }

  ds._lastBackendGrowth = now.toISOString();
  return changed ? ds : null;
}

/**
 * Parse LLM proactive reply: extract [[TYPE:...]] markers, separate message text,
 * and handle malformed raw TYPE: prefix fallback.
 * Returns { message, actionType, actions: { litter?, diary?, todo?, email? } }
 * where actions.diary is { title, mood, body } for structured diary format.
 */
function parseProactiveReply(content) {
  let message = content;
  const actions = {};

  // ── Pass 1: Match [[TYPE:内容]] standard markers ──
  const markerRegex = /\[\[(\w+):([\s\S]*?)\]\]/gi;
  let match;
  while ((match = markerRegex.exec(content)) !== null) {
    const type = match[1].toLowerCase();
    const body = match[2].trim();
    if (!actions[type]) {
      actions[type] = body;
    }
    message = message.replace(match[0], '');
  }

  // ── Pass 2: Fallback — raw LITTER:/DIARY:/MESSAGE: prefix (no brackets) ──
  const fallbackTypes = ['LITTER', 'DIARY', 'MESSAGE', 'EMAIL', 'TODO'];
  for (const fb of fallbackTypes) {
    const fbRegex = new RegExp('(?:^|\\n)\\s*' + fb + ':\\s*(.+?)(?=\\n|$)', 'im');
    const fbMatch = message.match(fbRegex);
    if (fbMatch) {
      const fbType = fb.toLowerCase();
      if (!actions[fbType]) {
        console.warn('[proactive] LLM used raw ' + fb + ': instead of [[' + fb + ':]] — auto-corrected');
        actions[fbType] = fbMatch[1].trim();
      }
      message = message.replace(fbMatch[0], '');
    }
  }

  // ── Pass 3: Parse DIARY sub-fields (标题|心情|正文) ──
  if (actions.diary && typeof actions.diary === 'string') {
    const parts = actions.diary.split('|').map(function(s) { return s.trim(); });
    if (parts.length >= 3) {
      actions.diary = {
        title: parts[0].substring(0, 15),
        mood: parts[1] || '平静',
        body: parts.slice(2).join('|')
      };
    } else {
      // Compat: old format — no title/mood
      actions.diary = {
        title: actions.diary.substring(0, 15),
        mood: '平静',
        body: actions.diary
      };
    }
  }

  // ── Final: strip any residual markers and prefixes ──
  message = message
    .replace(/\[\[\w+:[\s\S]*?\]\]/g, '')
    .replace(/^(MESSAGE|LITTER|DIARY|EMAIL|TODO):\s*/gmi, '')
    .trim();

  // Determine primary action type (for push notification tag matching)
  let actionType = 'message';
  if (actions.email) actionType = 'email';
  else if (actions.todo) actionType = 'todo';
  else if (actions.litter) actionType = 'litter';
  else if (actions.diary) actionType = 'diary';

  if (message) {
    console.log('[proactive] Parsed — message: ' + message.substring(0, 80) + ' | actions: ' + Object.keys(actions).join(','));
  } else {
    console.log('[proactive] Parsed — no message | actions: ' + Object.keys(actions).join(','));
  }

  return { message: message, actionType: actionType, actions: actions };
}

