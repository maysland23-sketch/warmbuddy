// In-memory config cache (reduces Supabase roundtrips for cron)
let _configsCache = null;
let _configsCacheTime = 0;
const CONFIGS_CACHE_TTL = 15000; // 15s

async function loadProjectConfigs() {
  if (supabase) {
    try {
      // Use cache if fresh
      if (_configsCache && (Date.now() - _configsCacheTime) < CONFIGS_CACHE_TTL) {
        return _configsCache;
      }
      const { data, error } = await supabase.from('project_configs').select('project_id, config');
      if (error) throw error;
      const configs = {};
      for (const row of (data || [])) {
        configs[row.project_id] = row.config || {};
      }
      _configsCache = configs;
      _configsCacheTime = Date.now();
      return configs;
    } catch (e) {
      console.error('[supabase] loadProjectConfigs error:', e.message);
      // Fallback to file on error
    }
  }
  // File-based fallback
  try { return JSON.parse(fs.readFileSync(CONFIGS_FILE, 'utf-8')); } catch { return {}; }
}

/**
 * Load a single project's config directly from Supabase, bypassing the in-memory cache.
 * Used for enabled-state checks where stale cache is unacceptable.
 * @param {string} projectId
 * @returns {object|null} the project config, or null if not found
 */
async function loadProjectConfig(projectId) {
  if (!supabase || !projectId) return null;
  try {
    const { data, error } = await supabase
      .from('project_configs')
      .select('config')
      .eq('project_id', projectId)
      .single();
    if (error || !data) return null;
    return data.config || {};
  } catch (e) {
    console.error('[supabase] loadProjectConfig error:', e.message);
    return null;
  }
}

/**
 * Check if a project's AI API is enabled.
 * Bypasses all caches — queries Supabase directly each time.
 * Defaults to enabled (true) when the enabled field is missing (backward compatibility).
 * @param {string} projectId
 * @returns {boolean}
 */
