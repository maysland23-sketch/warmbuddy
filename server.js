/**
 * Safe fetch wrapper — uses native https module for openrouter.ai domains
 * to work around a Node.js undici bug where the Authorization header is
 * silently dropped for certain hosts (HTTP/2 ALPN negotiation issue).
 * All other domains use the standard global fetch().
 *
 * @param {string} url - Full URL to fetch
 * @param {object} opts - { method, headers, body?, stream? }
 *   stream: if true, returns a response with body.getReader() for SSE streaming
 * @returns {Promise<{ok:boolean, status:number, text:()=>Promise<string>, json:()=>Promise<any>, body?:{getReader:fn}}>}
 */
async function safeFetch(url, opts = {}) {
  if (!url.toLowerCase().includes('openrouter')) {
    return fetch(url, opts);
  }

  // Native https for OpenRouter — undici drops Authorization header
  const https = require('https');
  const u = new URL(url);
  const { method = 'GET', headers = {}, body, stream } = opts;

  console.log(`[safe-fetch] Native HTTPS ${method} ${u.hostname}${u.pathname} stream=${!!stream}`);

  return new Promise((resolve, reject) => {
    const reqOpts = {
      hostname: u.hostname,
      path: u.pathname + u.search,
      method,
      headers: { ...headers, 'User-Agent': 'WarmBuddy/1.0' }
    };
    // Route through proxy if configured
    if (OUTBOUND_PROXY) {
      reqOpts.agent = new HttpsProxyAgent(OUTBOUND_PROXY);
    }
    const req = https.request(reqOpts, (resp) => {
      const respHeaders = {};
      for (const [k, v] of Object.entries(resp.headers)) {
        respHeaders[k] = Array.isArray(v) ? v.join(', ') : v;
      }

      if (stream) {
        // Streaming mode: build a ReadableStream from the native response
        const rs = new ReadableStream({
          start(controller) {
            resp.on('data', chunk => controller.enqueue(chunk));
            resp.on('end', () => controller.close());
            resp.on('error', err => controller.error(err));
          },
          cancel() { resp.destroy(); }
        });
        resolve({
          ok: resp.statusCode >= 200 && resp.statusCode < 300,
          status: resp.statusCode,
          headers: new Map(Object.entries(respHeaders)),
          body: rs  // has getReader() natively
        });
      } else {
        // Non-streaming: buffer entire body
        const chunks = [];
        resp.on('data', chunk => chunks.push(chunk));
        resp.on('end', () => {
          const rawBody = Buffer.concat(chunks).toString('utf-8');
          resolve({
            ok: resp.statusCode >= 200 && resp.statusCode < 300,
            status: resp.statusCode,
            headers: new Map(Object.entries(respHeaders)),
            text: () => Promise.resolve(rawBody),
            json: () => Promise.resolve(JSON.parse(rawBody))
          });
        });
      }
    });

    req.on('error', (err) => reject(err));

    if (body) {
      req.write(body);
    }
    req.end();
  });
}

/**
 * Detect API format from endpoint URL.
 * Uses PATH structure first (most reliable), then domain fallback.
 */
function detectProvider(endpoint) {
  if (!endpoint) return 'anthropic';
  const url = endpoint.toLowerCase();
  // Path-based detection (most reliable — different APIs use different path patterns)
  // Anthropic Messages API: /v1/messages or /anthropic/v1/messages
  if (url.includes('/messages') && !url.includes('/chat/completions')) return 'anthropic';
  // OpenAI Chat Completions API: /v1/chat/completions
  if (url.includes('/chat/completions')) return 'openai';
  // Domain-based fallback
  if (url.includes('anthropic') || url.includes('claude')) return 'anthropic';
  if (url.includes('deepseek')) return 'deepseek';
  if (url.includes('openai') || url.includes('openrouter')) return 'openai';
  return 'openai';
}

/**
 * Build auth headers based on provider format and actual host.
 * DeepSeek always uses Bearer token even for Anthropic-format endpoints.
 */
function getAuthHeaders(provider, endpoint, apiKey) {
  const host = (endpoint || '').toLowerCase();
  const key = (apiKey || '').trim();

  // DeepSeek-hosted APIs always use Bearer auth
  if (host.includes('deepseek')) {
    return { 'Content-Type': 'application/json', 'Authorization': `Bearer ${key}` };
  }
  // Standard Anthropic auth
  if (provider === 'anthropic') {
    return { 'Content-Type': 'application/json', 'x-api-key': key, 'anthropic-version': '2023-06-01' };
  }
  // OpenRouter uses Bearer auth + recommended headers
  if (host.includes('openrouter') || provider === 'openrouter') {
    const headers = {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${key}`,
      'HTTP-Referer': 'https://warmbuddy.vercel.app',
      'X-Title': 'WarmBuddy'
    };
    return headers;
  }
  // Standard OpenAI-compatible auth (GLM, OpenAI, etc.)
  return { 'Content-Type': 'application/json', 'Authorization': `Bearer ${key}` };
}

/**
 * Build request body based on provider
 */
function buildRequestBody(provider, model, messages, stream) {
  switch (provider) {
    case 'anthropic': {
      // Convert messages format for Anthropic
      const systemMsg = messages.find(m => m.role === 'system');
      const chatMessages = messages.filter(m => m.role !== 'system');
      const body = {
        model: model || 'claude-sonnet-4-6',
        max_tokens: 4096,
        messages: chatMessages.map(m => ({
          role: m.role === 'ai' ? 'assistant' : m.role,
          content: m.content
        })),
        stream: stream
      };
      if (systemMsg) body.system = systemMsg.content;
      return body;
    }
    case 'deepseek':
    case 'openai':
    default: {
      return {
        model: model || (provider === 'deepseek' ? 'deepseek-chat' : 'gpt-4o'),
        messages: messages.map(m => ({
          role: m.role === 'ai' ? 'assistant' : m.role,
          content: m.content
        })),
        stream: stream,
        max_tokens: 4096
      };
    }
  }
}

/**
 * Parse a single SSE chunk for each provider
 */
function parseStreamChunk(provider, chunk) {
  switch (provider) {
    case 'anthropic': {
      try {
        const json = JSON.parse(chunk);
        // Handle error events
        if (json.type === 'error') {
          return { error: json.error?.message || JSON.stringify(json.error) };
        }
        if (json.type === 'content_block_delta' && json.delta?.text != null) {
          return { text: json.delta.text };
        }
        if (json.type === 'message_start' && json.message?.usage) {
          return { usage: json.message.usage };
        }
        if (json.type === 'message_delta' && json.usage) {
          return { usage: json.usage };
        }
        return null;
      } catch { return null; }
    }
    case 'deepseek':
    case 'openai':
    default: {
      try {
        const json = JSON.parse(chunk);
        // Handle error events
        if (json.error) {
          return { error: json.error.message || JSON.stringify(json.error) };
        }
        if (json.choices && json.choices[0]?.delta?.content != null) {
          const result = { text: json.choices[0].delta.content };
          if (json.usage) result.usage = json.usage;
          return result;
        }
        if (json.usage) {
          return { usage: json.usage };
        }
        return null;
      } catch { return null; }
    }
  }
}

/**
 * Extract full response content from non-streaming response
 */
function extractResponseContent(provider, data) {
  // Check for API error in response body first
  if (data.error) {
    const errMsg = data.error.message || JSON.stringify(data.error);
    return { content: '', error: errMsg, usage: null };
  }
  switch (provider) {
    case 'anthropic': {
      if (data.content && Array.isArray(data.content)) {
        return {
          content: data.content.map(c => c.text || '').join(''),
          usage: data.usage || null
        };
      }
      return { content: '', usage: null };
    }
    case 'deepseek':
    case 'openai':
    default: {
      if (data.choices && data.choices[0]?.message?.content != null) {
        return {
          content: data.choices[0].message.content,
          usage: data.usage || null
        };
      }
      return { content: '', usage: null };
    }
  }
}

